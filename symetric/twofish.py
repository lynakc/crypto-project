# ── Public API ───
def encrypt(message, key):
   
    key_bytes = [ord(c) for c in key]
    K, S = _key_schedule(key_bytes)

    data = _pad(message.encode("utf-8"))

    result = []
    for i in range(0, len(data), 16):
        block = list(data[i:i+16])
        result += _encrypt_block(block, K, S)

    return bytes(result).hex().upper()


def decrypt(ciphertext, key):
    
    key_bytes = [ord(c) for c in key]
    K, S = _key_schedule(key_bytes)

    data = bytes.fromhex(ciphertext)

    result = []
    for i in range(0, len(data), 16):
        block = list(data[i:i+16])
        result += _decrypt_block(block, K, S)

    return _unpad(bytes(result)).decode("utf-8")


