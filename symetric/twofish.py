# ── GF(2^8)  ─────────
def _gf_mul(a, b):
    result = 0
    while b:
        if b & 1:
            result ^= a
        a <<= 1
        if a & 0x100:
            a ^= 0x169
        b >>= 1
    return result & 0xFF


# ── MDS matrix multiply  ────
MDS = [
    [0x01, 0xEF, 0x5B, 0x5B],
    [0x5B, 0xEF, 0xEF, 0x01],
    [0xEF, 0x5B, 0x01, 0xEF],
    [0xEF, 0x01, 0xEF, 0x5B],
]

def _mds_mul(v):
   
    result = [0] * 4
    for i in range(4):
        for j in range(4):
            result[i] ^= _gf_mul(MDS[i][j], v[j])
    return result


# ── Reed-Solomon step (key schedule) ───
RS = [
    [0x01, 0xA4, 0x55, 0x87, 0x5A, 0x58, 0xDB, 0x9E],
    [0xA4, 0x56, 0x82, 0xF3, 0x1E, 0xC6, 0x68, 0xE5],
    [0x02, 0xA1, 0xFC, 0xC1, 0x47, 0xAE, 0x3D, 0x19],
    [0xA4, 0x55, 0x87, 0x5A, 0x58, 0xDB, 0x9E, 0x03],
]

def _rs_mul(v):
    result = [0] * 4
    for i in range(4):
        for j in range(8):
            result[i] ^= _gf_mul(RS[i][j], v[j])
    return result


# ── h function ────
def _h(x_bytes, L):
   
    y = list(x_bytes)
    k = len(L)

    if k >= 4:
        y = [Q1[y[0]] ^ L[3][0],
             Q0[y[1]] ^ L[3][1],
             Q0[y[2]] ^ L[3][2],
             Q1[y[3]] ^ L[3][3]]
    if k >= 3:
        y = [Q1[y[0]] ^ L[2][0],
             Q1[y[1]] ^ L[2][1],
             Q0[y[2]] ^ L[2][2],
             Q0[y[3]] ^ L[2][3]]
    # always k >= 2 for 128-bit key (k=2)
    y = [Q0[Q0[y[0]] ^ L[1][0]] ^ L[0][0],
         Q0[Q1[y[1]] ^ L[1][1]] ^ L[0][1],
         Q1[Q0[y[2]] ^ L[1][2]] ^ L[0][2],
         Q1[Q1[y[3]] ^ L[1][3]] ^ L[0][3]]

    return _mds_mul(y)


# ── Key schedule ────
def _key_schedule(key_bytes):
    N = len(key_bytes) // 4         
    k = N // 2                       

    Me = []   
    Mo = []   
    S  = []  

    for i in range(k):
        me = key_bytes[8*i   : 8*i+4]
        mo = key_bytes[8*i+4 : 8*i+8]
        Me.append(me)
        Mo.append(mo)
        s_word = _rs_mul(key_bytes[8*i : 8*i+8])
        S.insert(0, s_word)

    # generate 40 subkeys
    rho = 0x01010101
    K = []
    for i in range(20):
        A = _int_from_bytes(_h([( 2*i    * rho >> s) & 0xFF for s in (0,8,16,24)], Me))
        B = _int_from_bytes(_h([(( 2*i+1) * rho >> s) & 0xFF for s in (0,8,16,24)], Mo))
        B = _rotl32(B, 8)
        K.append((A + B) & 0xFFFFFFFF)
        K.append(_rotl32((A + 2*B) & 0xFFFFFFFF, 9))

    return K, S


# ── g function (uses S-box material) ───
def _g(x, S):
    x_bytes = [(x >> s) & 0xFF for s in (0, 8, 16, 24)]
    result  = _h(x_bytes, S)
    return _int_from_bytes(result)


# ── 32-bit helpers ──
def _rotl32(x, n):
    return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF

def _rotr32(x, n):
    return ((x >> n) | (x << (32 - n))) & 0xFFFFFFFF

def _int_from_bytes(b):
    return b[0] | (b[1] << 8) | (b[2] << 16) | (b[3] << 24)

def _int_to_bytes(n):
    return [(n >> s) & 0xFF for s in (0, 8, 16, 24)]


# ── Single block encrypt / decrypt ───
def _encrypt_block(block_bytes, K, S):
   
    words = [struct.unpack_from('<I', bytes(block_bytes[4*i:4*i+4]))[0] ^ K[i]
             for i in range(4)]
    a, b, c, d = words

    for r in range(16):
        t0 = _g(a, S)
        t1 = _g(_rotl32(b, 8), S)
        c  = _rotr32(c ^ ((t0 + t1 + K[2*r+8])  & 0xFFFFFFFF), 1)
        d  = _rotl32(d, 1) ^ ((t0 + 2*t1 + K[2*r+9]) & 0xFFFFFFFF)
        a, b, c, d = c, d, a, b

    a, b, c, d = c, d, a, b
    result = []
    for val, ki in zip([a, b, c, d], [4, 5, 6, 7]):
        val ^= K[ki]
        result += _int_to_bytes(val)
    return result


def _decrypt_block(block_bytes, K, S):
    
    words = [struct.unpack_from('<I', bytes(block_bytes[4*i:4*i+4]))[0] ^ K[i+4]
             for i in range(4)]
    a, b, c, d = words

    for r in range(15, -1, -1):
        t0 = _g(a, S)
        t1 = _g(_rotl32(b, 8), S)
        c  = _rotl32(c, 1) ^ ((t0 + t1   + K[2*r+8]) & 0xFFFFFFFF)
        d  = _rotr32(d ^ ((t0 + 2*t1 + K[2*r+9]) & 0xFFFFFFFF), 1)
        a, b, c, d = c, d, a, b


    a, b, c, d = c, d, a, b
    result = []
    for val, ki in zip([a, b, c, d], [0, 1, 2, 3]):
        val ^= K[ki]
        result += _int_to_bytes(val)
    return result


# ── PKCS7 padding ────
def _pad(data: bytes) -> bytes:
    pad_len = 16 - (len(data) % 16)
    return data + bytes([pad_len] * pad_len)

def _unpad(data: bytes) -> bytes:
    pad_len = data[-1]
    return data[:-pad_len]


